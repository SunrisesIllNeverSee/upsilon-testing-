# ---------------------------------------------------------------------------

# Reusable S0 fixture for probes (minimal Ameresco-like state).
_PROBE_AGREEMENT = "probe-agreement"
_PROBE_SECTION_REFS = {
    "financial_covenant.leverage_ratio": "Section 7.10(a)",
}


