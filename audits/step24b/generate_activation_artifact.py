"""Step 24B-R Phase 8: Generate the runtime activation artifact.

Produces ``results/current/step24b_runtime_activation.json`` from the
ACTUAL current runtime execution.  No hand-entered PASS statuses —
every value is derived from runtime results.

The artifact is generated by running ``run_semantic_pipeline_v2`` on
the designated real EDGAR Ameresco chain and extracting all required
fields from the runtime result objects (SpineResult, AmendmentEvidence,
AuthorizedTransformation, IdentityResolutionResult,
SemanticTransformationProof, LineageEdge, AuthorityGateResult).

Usage:
    python3 -m audits.step24b.generate_activation_artifact

Or via the test suite, which calls ``generate_artifact()`` directly.
"""
